#!/usr/bin/env node
/**
 * Regenerates src/accounts.ts from `offckb accounts`.
 *
 * Addresses and lock args only — private keys are deliberately NOT written to
 * disk here. The app asks for a key when you sign something and keeps it in
 * sessionStorage, so nothing secret can end up in a commit. Print the keys for
 * yourself with:  offckb accounts --show-private-keys
 */
const { execFileSync } = require("child_process");
const { writeFileSync } = require("fs");
const { join } = require("path");

const cli = process.platform === "win32" ? "offckb.cmd" : "offckb";
const out = execFileSync(cli, ["accounts"], { encoding: "utf8" });

const accounts = [];
const blocks = out.split(/- "#":\s*/).slice(1);
for (const block of blocks) {
  const index = Number(block.match(/^(\d+)/)?.[1]);
  const address = block.match(/address:\s*(\S+)/)?.[1];
  const lockArgs = block.match(/lock_arg:\s*(0x[0-9a-f]+)/i)?.[1];
  if (Number.isInteger(index) && address && lockArgs)
    accounts.push({ index, address, lockArgs });
}

if (accounts.length === 0) {
  console.error("No accounts parsed. Is offckb installed and the devnet set up?");
  process.exit(1);
}

const file = `// Generated by \`npm run accounts\` - do not edit by hand.
// Devnet test accounts from OffCKB. Addresses only; never private keys.
export type DevAccount = { index: number; address: string; lockArgs: string };

export const DEV_ACCOUNTS: DevAccount[] = ${JSON.stringify(accounts, null, 2)};
`;

writeFileSync(join(__dirname, "..", "src", "accounts.ts"), file);
console.log(`Wrote src/accounts.ts with ${accounts.length} devnet accounts.`);
